ok(!reward.includes("body.credits"),"Client cannot directly set credits");
const migration=read("migrations/012_game_modes.sql");
ok(migration.includes("WHERE pin=p_pin FOR UPDATE"),"One room serializes concurrent rewards");
ok(migration.includes("UNIQUE(player_id,question_index)"),"At most one reward per player per question");
ok(migration.includes("AND is_correct"),"Only correct answers eligible");
ok(migration.includes("p_target<>p_player"),"Self theft excluded");
ok(migration.includes("LEAST(40,credits)"),"Chests cannot make victim negative");
ok(migration.includes("LEAST(60,credits/3)"),"Virtual hack losses bounded");
ok(migration.includes("room_pin=p_pin"),"Target ownership constrained to room");
ok(migration.includes("served_count")&&migration.includes("cafe_level"),"Café progress is durable");
ok(migration.includes("fish_count"),"Fish collection tracked");
